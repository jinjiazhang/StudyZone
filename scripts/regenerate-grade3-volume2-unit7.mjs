let choiceCounter = 0;
const choiceTargets = [1, 3, 0, 2, 2, 0, 3, 1];
const choice = (question, options, correct, difficulty = 1) => {
  const target = choiceTargets[choiceCounter++ % choiceTargets.length];
  const next = options.slice();
  const [right] = next.splice(correct, 1);
  next.splice(target, 0, right);
  return ex('single_choice', { question, options: next }, { correctIndex: target }, difficulty);
};
