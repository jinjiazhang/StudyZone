let seed = 20260618;
function rand() {
  seed = (seed * 1664525 + 1013904223) >>> 0;
  return seed / 2 ** 32;
}

function shuffle(items) {
  const copy = [...items];
  for (let i = copy.length - 1; i > 0; i -= 1) {
    const j = Math.floor(rand() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}

function choice(question, correct, distractors, difficulty = 1) {
  const options = shuffle([correct, ...distractors]);
  return {
    type: 'single_choice',
    prompt: { question, options },
    answer: { correctIndex: options.indexOf(correct) },
    difficulty,
  };
}

function geometry(question, correctLabel, otherLabels, difficulty = 1) {
  const options = shuffle([correctLabel, ...otherLabels]).map((label, index) => ({
    id: `g${index + 1}`,
    label,
  }));
  return {
    type: 'geometry_choice',
    prompt: { question, options },
    answer: { correctOptionId: options.find((option) => option.label === correctLabel).id },
    difficulty,
  };
}

function drag(statement, fills, tokens, difficulty = 2) {
  const shuffled = shuffle(tokens);
  while (containsContiguous(shuffled, fills)) {
    shuffled.push(shuffled.shift());
  }
  return {
    type: 'math_drag_fill',
    prompt: { statement, tokens: shuffled },
    answer: { fills },
    difficulty,
  };
}

function multi(statement, blanks, values, difficulty = 2) {
  return {
    type: 'multi_numeric_input',
    prompt: {
      statement,
      blanks: blanks.map((blank, index) => ({ id: `b${index + 1}`, label: blank })),
    },
    answer: { values, tolerances: values.map(() => 0) },
    difficulty,
  };
}

function order(instruction, orderedTexts, difficulty = 2) {
  const answerIds = orderedTexts.map((_, index) => `s${index + 1}`);
  let items = orderedTexts.map((text, index) => ({ id: answerIds[index], text }));
  items = shuffle(items);
  if (items.map((item) => item.id).join('|') === answerIds.join('|')) items.reverse();
  return {
    type: 'order_sequence',
    prompt: { instruction, items },
    answer: { orderedIds: answerIds },
    difficulty,
  };
}

function match(leftTexts, pairs, rightTexts, difficulty = 2) {
  const left = leftTexts.map((text, index) => ({ id: `l${index + 1}`, text }));
  let right = rightTexts.map((text, index) => ({ id: `r${index + 1}`, text }));
  const pairMap = {};
  for (let i = 0; i < leftTexts.length; i += 1) pairMap[left[i].id] = `r${pairs[i] + 1}`;
  right = shuffle(right);
  let same = right.filter((item, index) => pairMap[left[index]?.id] === item.id).length;
  while (same >= Math.max(1, Math.ceil(Math.min(left.length, right.length) / 2))) {
    right = [...right.slice(1), right[0]];
    same = right.filter((item, index) => pairMap[left[index]?.id] === item.id).length;
  }
  return {
    type: 'match_pairs',
    prompt: { left, right },
    answer: { pairs: pairMap },
    difficulty,
  };
}

function containsContiguous(haystack, needle) {
  if (!needle.length || needle.length > haystack.length) return false;
  for (let i = 0; i <= haystack.length - needle.length; i += 1) {
    if (needle.every((item, index) => haystack[i + index] === item)) return true;
  }
  return false;
}

function table(question, columns, rows, answer, difficulty = 2) {
  return {
    type: 'table_read',
    prompt: { question, columns, rows },
    answer,
    difficulty,
  };
}

