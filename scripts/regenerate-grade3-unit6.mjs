function addLesson(file, title, exercises) {
  const orderIndex = lessons.length;
  lessons.push({ file, orderIndex, title, icon: icons[orderIndex] });
  lessonFiles.set(file, { exercises });
}

function choice(type, prompt, options, correct, difficulty = 1) {
  return {
    type,
    prompt: { ...prompt, options },
    answer: { correctIndex: options.indexOf(correct) },
    difficulty,
  };
}

function pinyin(character, correct, options, hint, difficulty = 1) {
  return choice(
    'pinyin_choice',
    { character, hint, narrationText: `选出“${character}”的正确读音。` },
    options,
    correct,
    difficulty,
  );
}

function writeChar(character, pinyinText, sentence, difficulty = 2) {
  return {
    type: 'pinyin_to_word',
    prompt: {
      pinyin: pinyinText,
      sentence,
      blankPlaceholder: '__',
      character,
      narrationText: `看拼音写字：${sentence.replace('__', '空格')}`,
      allowedMistakes: 3,
      leniency: 1.1,
    },
    answer: { character },
    difficulty,
  };
}

function wordBuild(character, tokens, acceptedSets, instruction, difficulty = 2) {
  return {
    type: 'word_build',
    prompt: { character, tokens, targetCount: acceptedSets[0].length, instruction },
    answer: { acceptedSets },
    difficulty,
  };
}

function single(question, options, correct, difficulty = 1) {
  return choice('single_choice', { question }, options, correct, difficulty);
}

function bank(source, tokens, ordered, difficulty = 2) {
  return {
    type: 'word_bank',
    prompt: { source, tokens },
    answer: { ordered },
    difficulty,
  };
}

function pairs(leftItems, rightItems, difficulty = 2) {
  const left = leftItems.map(([id, text]) => ({ id, text }));
  const right = rightItems.map(([id, text]) => ({ id, text }));
  const answer = {};
  leftItems.forEach(([id], index) => {
    answer[id] = rightItems.find(([rid]) => rid === `r${index + 1}`)?.[0] ?? `r${index + 1}`;
  });
  return { type: 'match_pairs', prompt: { left, right }, answer: { pairs: answer }, difficulty };
}

function exactPairs(entries, leftOrder, rightOrder, difficulty = 2) {
  const left = leftOrder.map((i) => ({ id: `l${i}`, text: entries[i - 1][0] }));
  const right = rightOrder.map((i) => ({ id: `r${i}`, text: entries[i - 1][1] }));
  const answer = Object.fromEntries(entries.map((_, i) => [`l${i + 1}`, `r${i + 1}`]));
  return { type: 'match_pairs', prompt: { left, right }, answer: { pairs: answer }, difficulty };
}

function tf(statement, value, difficulty = 1) {
  return {
    type: 'true_false',
    prompt: { statement, trueLabel: '对', falseLabel: '错' },
    answer: { value },
    difficulty,
  };
}

function reading(title, passage, questions, correctIndices, difficulty = 2, imageUrl) {
  return {
    type: 'reading_comprehension',
    prompt: { title, passage, ...(imageUrl ? { imageUrl } : {}), questions },
    answer: { correctIndices },
    difficulty,
  };
}

